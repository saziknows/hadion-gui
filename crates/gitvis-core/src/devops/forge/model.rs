/// One comment.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Note {
    pub author: Person,
    pub body: String,
    pub created: Option<i64>,
    /// Generated by the forge ("added 1 commit").
    pub system: bool,
}

/// A discussion thread.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Thread {
    pub id: String,
    pub resolvable: bool,
    pub resolved: bool,
    pub notes: Vec<Note>,
}

/// Summary of a list of threads.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ThreadStats {
    /// Threads with at least one human note.
    pub threads: usize,
    pub notes: usize,
    pub resolvable: usize,
    pub unresolved: usize,
    pub system: usize,
}

pub fn thread_stats(threads: &[Thread]) -> ThreadStats {
    let mut s = ThreadStats::default();
    for t in threads {
        let human = t.notes.iter().filter(|n| !n.system).count();
        s.system += t.notes.len() - human;
        if human == 0 {
            continue;
        }
        s.threads += 1;
        s.notes += human;
        if t.resolvable {
            s.resolvable += 1;
            if !t.resolved {
                s.unresolved += 1;
            }
        }
    }
    s
}

/// One changed file.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct FileChange {
    pub old_path: String,
    pub new_path: String,
    pub new_file: bool,
    pub deleted: bool,
    pub renamed: bool,
    pub additions: u64,
    pub deletions: u64,
}

/// `(additions, deletions)` of a unified diff body.
pub fn count_diff(diff: &str) -> (u64, u64) {
    let (mut a, mut d) = (0, 0);
    for l in diff.lines() {
        if l.starts_with("+++") || l.starts_with("---") {
            continue;
        }
        if l.starts_with('+') {
            a += 1;
        } else if l.starts_with('-') {
            d += 1;
        }
    }
    (a, d)
}

/// A pipeline (GitLab) or run (Azure Pipelines).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Pipeline {
    pub id: u64,
    /// GitLab `iid`, Azure `buildNumber`.
    pub number: String,
    /// Azure pipeline (definition) name; GitLab pipeline name if set.
    pub name: String,
    pub definition_id: Option<u64>,
    /// The forge's own status words (`running`, `failed`, `manual`,
    /// `partially succeeded`).
    pub status: String,
    pub outcome: Outcome,
    /// Branch or ref, `refs/heads/` removed.
    pub reference: String,
    pub sha: String,
    /// GitLab `source` (`push`, `merge_request_event`), Azure `reason`.
    pub source: String,
    pub created: Option<i64>,
    pub started: Option<i64>,
    pub finished: Option<i64>,
    /// Seconds.
    pub duration: Option<i64>,
    pub queued: Option<i64>,
    pub user: String,
    pub web_url: String,
}

impl Default for Pipeline {
    fn default() -> Self {
        Self {
            id: 0,
            number: String::new(),
            name: String::new(),
            definition_id: None,
            status: String::new(),
            outcome: Outcome::Unknown,
            reference: String::new(),
            sha: String::new(),
            source: String::new(),
            created: None,
            started: None,
            finished: None,
            duration: None,
            queued: None,
            user: String::new(),
            web_url: String::new(),
        }
    }
}

/// A job (GitLab) or timeline record (Azure: stage, job or task).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Job {
    pub id: u64,
    /// Azure record id (a GUID); empty on GitLab.
    pub record: String,
    pub name: String,
    /// GitLab stage; Azure record type (`Stage`, `Job`, `Task`).
    pub stage: String,
    pub status: String,
    pub outcome: Outcome,
    pub started: Option<i64>,
    pub finished: Option<i64>,
    pub duration: Option<i64>,
    pub queued: Option<i64>,
    pub allow_failure: bool,
    pub failure_reason: String,
    pub web_url: String,
    pub runner: String,
    /// Nesting for Azure records (stage 0, job 1, task 2).
    pub depth: u8,
    /// Azure log id; GitLab jobs always have a trace (`Some(id)`).
    pub log_id: Option<u64>,
    pub errors: u32,
    pub warnings: u32,
    /// Azure issue messages (errors and warnings).
    pub issues: Vec<String>,
}

impl Default for Job {
    fn default() -> Self {
        Self {
            id: 0,
            record: String::new(),
            name: String::new(),
            stage: String::new(),
            status: String::new(),
            outcome: Outcome::Unknown,
            started: None,
            finished: None,
            duration: None,
            queued: None,
            allow_failure: false,
            failure_reason: String::new(),
            web_url: String::new(),
            runner: String::new(),
            depth: 0,
            log_id: None,
            errors: 0,
            warnings: 0,
            issues: Vec::new(),
        }
    }
}

/// Seconds since the epoch, `None` for empty or year-1 placeholders.
pub fn time(s: Option<&str>) -> Option<i64> {
    let (t, _) = parse_timestamp(s?)?;
    (t > 86_400).then_some(t)
}

/// `b - a` in whole seconds when both are known.
pub fn span(a: Option<i64>, b: Option<i64>) -> Option<i64> {
    Some((b? - a?).max(0))
}

/// `refs/heads/main` → `main`.
pub fn short_ref(r: &str) -> String {
    r.strip_prefix("refs/heads/").unwrap_or(r).to_owned()
}

/// GitLab pipeline and job statuses.
pub fn gitlab_outcome(status: &str) -> Outcome {
    match status {
        "success" => Outcome::Success,
        "failed" => Outcome::Failure,
        "canceled" | "canceling" => Outcome::Cancelled,
        "skipped" => Outcome::Skipped,
        "running" => Outcome::InProgress,
        "created"
        | "pending"
        | "preparing"
        | "waiting_for_resource"
        | "scheduled"
        | "waiting_for_callback" => Outcome::Queued,
        "manual" => Outcome::Neutral,
        _ => Outcome::Unknown,
    }
}

/// Azure build / timeline `status` (or `state`) plus `result`.
pub fn azure_outcome(status: &str, result: &str) -> Outcome {
    match status {
        "inProgress" | "cancelling" => return Outcome::InProgress,
        "notStarted" | "postponed" | "pending" => return Outcome::Queued,
        _ => {}
    }
    match result {
        "succeeded" => Outcome::Success,
        "failed" => Outcome::Failure,
        "canceled" | "abandoned" => Outcome::Cancelled,
        "skipped" => Outcome::Skipped,
        "partiallySucceeded" | "succeededWithIssues" => Outcome::Neutral,
        _ if status == "completed" => Outcome::Unknown,
        _ => Outcome::Queued,
    }
}

/// `partiallySucceeded` → `partially succeeded`, `waiting_for_resource` →
/// `waiting for resource`, `individualCI` → `individual CI`.
pub fn words(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut tokens: Vec<String> = Vec::new();
    let mut cur = String::new();
    for (i, &c) in chars.iter().enumerate() {
        if matches!(c, '_' | ' ' | '-') {
            if !cur.is_empty() {
                tokens.push(std::mem::take(&mut cur));
            }
            continue;
        }
        if c.is_ascii_uppercase() && !cur.is_empty() {
            let prev_lower = chars[i - 1].is_ascii_lowercase() || chars[i - 1].is_ascii_digit();
            let prev_upper = chars[i - 1].is_ascii_uppercase();
            let next_lower = chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
            if prev_lower || (prev_upper && next_lower) {
                tokens.push(std::mem::take(&mut cur));
            }
        }
        cur.push(c);
    }
    if !cur.is_empty() {
        tokens.push(cur);
    }
    tokens
        .into_iter()
        .map(|t| {
            if t.chars().count() > 1 && t.chars().all(|c| c.is_ascii_uppercase()) {
                t
            } else {
                t.to_lowercase()
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn helpers() {
        assert_eq!(words("partiallySucceeded"), "partially succeeded");
        assert_eq!(words("waiting_for_resource"), "waiting for resource");
        assert_eq!(words("individualCI"), "individual CI");
        assert_eq!(words("HTTPServer"), "HTTP server");
        assert_eq!(words("inProgress"), "in progress");
        assert_eq!(short_ref("refs/heads/feature/x"), "feature/x");
        assert_eq!(
            short_ref("refs/merge-requests/5/merge"),
            "refs/merge-requests/5/merge"
        );
        assert_eq!(time(Some("0001-01-01T00:00:00")), None);
        assert!(time(Some("2026-10-26T04:50:27.3645819Z")).is_some());
        assert_eq!(span(Some(10), Some(70)), Some(60));
        assert_eq!(count_diff("@@ -1 +1 @@\n-a\n+b\n+c\n context"), (2, 1));
        assert_eq!(gitlab_outcome("manual"), Outcome::Neutral);
        assert_eq!(
            azure_outcome("completed", "partiallySucceeded"),
            Outcome::Neutral
        );
        assert_eq!(azure_outcome("inProgress", ""), Outcome::InProgress);
        assert_eq!(azure_outcome("completed", "failed"), Outcome::Failure);
        assert_eq!(Person::new("Ada", "ada").display(), "Ada (ada)");
        assert!(Person::new("", "ADA").is("ada"));
    }

    #[test]
    fn thread_summary() {
        let human = Note {
            body: "x".into(),
            ..Default::default()
        };
        let sys = Note {
            system: true,
            ..Default::default()
        };
        let threads = vec![
            Thread {
                resolvable: true,
                resolved: false,
                notes: vec![human.clone(), human.clone()],
                ..Default::default()
            },
            Thread {
                resolvable: true,
                resolved: true,
                notes: vec![human.clone()],
                ..Default::default()
            },
            Thread {
                notes: vec![sys],
                ..Default::default()
            },
        ];
        let s = thread_stats(&threads);
        assert_eq!(
            s,
            ThreadStats {
                threads: 2,
                notes: 3,
                resolvable: 2,
                unresolved: 1,
                system: 1
            }
        );
    }
}
