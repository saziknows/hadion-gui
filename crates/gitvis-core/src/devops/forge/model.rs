//! Forge-neutral models: what the Review and Actions pages show for a
//! GitLab merge request or an Azure DevOps pull request, and for their
//! pipelines and jobs. [`super::gitlab`] and [`super::azure`] convert their
//! JSON into these.

use crate::github::{Outcome, parse_timestamp};

/// A user as the forge names them.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Person {
    /// Display name.
    pub name: String,
    /// GitLab username, Azure unique name (usually an e-mail address).
    pub login: String,
}

impl Person {
    pub fn new(name: impl Into<String>, login: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            login: login.into(),
        }
    }

    /// `Ada Lovelace (@ada)`, or whichever part is known.
    pub fn display(&self) -> String {
        match (self.name.is_empty(), self.login.is_empty()) {
            (false, false) if self.name != self.login => format!("{} ({})", self.name, self.login),
            (false, _) => self.name.clone(),
            (true, false) => self.login.clone(),
            _ => "unknown".to_owned(),
        }
    }

    pub fn is(&self, login: &str) -> bool {
        !login.is_empty() && self.login.eq_ignore_ascii_case(login)
    }
}

/// A reviewer and (Azure DevOps) their vote.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Reviewer {
    pub person: Person,
    /// Azure vote: 10 approved, 5 approved with suggestions, 0 none,
    /// -5 waiting for author, -10 rejected. `None` on GitLab.
    pub vote: Option<i64>,
    pub required: bool,
    pub declined: bool,
}

/// The pipeline attached to a merge request.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct PipelineRef {
    pub id: u64,
    pub status: String,
    pub web_url: String,
}

/// A merge request (GitLab) or pull request (Azure DevOps).
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ChangeRequest {
    /// GitLab `iid` (`!12`), Azure `pullRequestId`.
    pub number: u64,
    pub title: String,
    pub description: String,
    pub author: Person,
    pub source: String,
    pub target: String,
    pub draft: bool,
    /// `opened`, `active`, …
    pub state: String,
    pub created: Option<i64>,
    pub updated: Option<i64>,
    pub web_url: String,
    /// Head commit of the source branch.
    pub sha: String,
    pub labels: Vec<String>,
    pub assignees: Vec<Person>,
    pub reviewers: Vec<Reviewer>,
    /// GitLab `detailed_merge_status` (`mergeable`, `not_approved`,
    /// `ci_still_running`, …), Azure `mergeStatus` (`succeeded`,
    /// `conflicts`, …).
    pub merge_status: String,
    pub conflicts: bool,
    /// Comments (GitLab `user_notes_count`).
    pub comments: u64,
    pub upvotes: u64,
    pub downvotes: u64,
    pub squash: bool,
    pub remove_source: bool,
    /// Merge when the pipeline succeeds (GitLab) / auto-complete (Azure).
    pub auto_merge: bool,
    pub pipeline: Option<PipelineRef>,
    /// `(completed, total)` task list items.
    pub tasks: Option<(u64, u64)>,
    /// GitLab `changes_count` (`"5"`, `"1000+"`), detail only.
    pub changes_count: Option<String>,
    /// Can the signed-in user merge it (detail only).
    pub can_merge: Option<bool>,
    pub merge_error: Option<String>,
    pub blocking_discussions_resolved: bool,
}

/// Approvals of a merge request.
